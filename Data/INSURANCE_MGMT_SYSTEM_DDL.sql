-- ############################################################################
-- SECTION 1: DATABASE & SCHEMAS
-- ############################################################################

CREATE DATABASE IF NOT EXISTS INSURANCE_MGMT_SYSTEM;

CREATE SCHEMA IF NOT EXISTS INSURANCE_MGMT_SYSTEM.CORE;
CREATE SCHEMA IF NOT EXISTS INSURANCE_MGMT_SYSTEM.PREMIUM;
CREATE SCHEMA IF NOT EXISTS INSURANCE_MGMT_SYSTEM.RISK;
CREATE SCHEMA IF NOT EXISTS INSURANCE_MGMT_SYSTEM.ANALYTICS;


-- ############################################################################
-- SECTION 2: CORE TABLES
-- ############################################################################

CREATE TABLE IF NOT EXISTS INSURANCE_MGMT_SYSTEM.CORE.AGENTS (
    AGENT_ID VARCHAR(20) PRIMARY KEY,
    AGENT_NAME VARCHAR(100),
    ROLE VARCHAR(30),
    REGION VARCHAR(50),
    BRANCH VARCHAR(50),
    HIRE_DATE DATE,
    SPECIALIZATION VARCHAR(50),
    PERFORMANCE_SCORE FLOAT,
    ACTIVE_POLICIES_COUNT INT,
    CERTIFICATIONS VARCHAR(200),
    ACTIVE_FLAG BOOLEAN DEFAULT TRUE,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS INSURANCE_MGMT_SYSTEM.CORE.CUSTOMERS (
    CUSTOMER_ID VARCHAR(20) PRIMARY KEY,
    FIRST_NAME VARCHAR(50),
    LAST_NAME VARCHAR(50),
    DATE_OF_BIRTH DATE,
    AGE INT,
    GENDER VARCHAR(10),
    MARITAL_STATUS VARCHAR(20),
    EMAIL VARCHAR(100),
    PHONE VARCHAR(20),
    ADDRESS VARCHAR(200),
    CITY VARCHAR(50),
    STATE VARCHAR(2),
    ZIP_CODE VARCHAR(10),
    OCCUPATION VARCHAR(50),
    ANNUAL_INCOME DECIMAL(12,2),
    CREDIT_SCORE INT,
    SMOKING_STATUS VARCHAR(10),
    BMI FLOAT,
    CUSTOMER_SINCE DATE,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS INSURANCE_MGMT_SYSTEM.CORE.POLICIES (
    POLICY_ID VARCHAR(20) PRIMARY KEY,
    CUSTOMER_ID VARCHAR(20),
    AGENT_ID VARCHAR(20),
    POLICY_TYPE VARCHAR(20),
    PLAN_TIER VARCHAR(20),
    POLICY_STATUS VARCHAR(20),
    START_DATE DATE,
    END_DATE DATE,
    PREMIUM_AMOUNT DECIMAL(12,2),
    COVERAGE_AMOUNT DECIMAL(14,2),
    DEDUCTIBLE DECIMAL(10,2),
    LOSS_RATIO FLOAT,
    PAYMENT_FREQUENCY VARCHAR(20),
    AUTO_RENEW BOOLEAN,
    UNDERWRITING_SCORE FLOAT,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS INSURANCE_MGMT_SYSTEM.CORE.CLAIMS (
    CLAIM_ID VARCHAR(20) PRIMARY KEY,
    POLICY_ID VARCHAR(20),
    CUSTOMER_ID VARCHAR(20),
    CLAIM_DATE DATE,
    REPORTED_DATE DATE,
    CLAIM_TYPE VARCHAR(30),
    CLAIM_STATUS VARCHAR(30),
    CLAIM_AMOUNT DECIMAL(12,2),
    APPROVED_AMOUNT DECIMAL(12,2),
    FRAUD_FLAG BOOLEAN DEFAULT FALSE,
    FRAUD_SCORE FLOAT,
    FRAUD_REASON VARCHAR(200),
    ASSIGNED_ADJUSTER VARCHAR(50),
    RESOLUTION_DATE DATE,
    DAYS_TO_RESOLVE INT,
    PRIORITY VARCHAR(10),
    ESCALATED BOOLEAN DEFAULT FALSE,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);


-- ############################################################################
-- SECTION 3: PREMIUM TABLES
-- ############################################################################

CREATE TABLE IF NOT EXISTS INSURANCE_MGMT_SYSTEM.PREMIUM.PREMIUM_FACTORS (
    FACTOR_ID VARCHAR(20) PRIMARY KEY,
    POLICY_TYPE VARCHAR(20),
    FACTOR_NAME VARCHAR(50),
    FACTOR_CATEGORY VARCHAR(30),
    FACTOR_VALUE VARCHAR(50),
    MULTIPLIER FLOAT,
    BASE_RATE DECIMAL(10,2),
    DESCRIPTION VARCHAR(200),
    EFFECTIVE_DATE DATE,
    ACTIVE_FLAG BOOLEAN DEFAULT TRUE,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS INSURANCE_MGMT_SYSTEM.PREMIUM.PLAN_TIERS (
    TIER_ID VARCHAR(20) PRIMARY KEY,
    POLICY_TYPE VARCHAR(20),
    PLAN_NAME VARCHAR(30),
    MONTHLY_PREMIUM DECIMAL(10,2),
    ANNUAL_PREMIUM DECIMAL(12,2),
    COVERAGE_LIMIT DECIMAL(14,2),
    DEDUCTIBLE DECIMAL(10,2),
    COPAY_PCT FLOAT,
    KEY_BENEFITS TEXT,
    RECOMMENDED_FOR VARCHAR(100),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS INSURANCE_MGMT_SYSTEM.PREMIUM.PREMIUM_CALCULATIONS (
    CALC_ID VARCHAR(20) PRIMARY KEY,
    CUSTOMER_ID VARCHAR(20),
    POLICY_TYPE VARCHAR(20),
    PLAN_TIER VARCHAR(20),
    CALC_DATE TIMESTAMP_NTZ,
    BASE_PREMIUM DECIMAL(10,2),
    AGE_FACTOR FLOAT,
    LOCATION_FACTOR FLOAT,
    HEALTH_FACTOR FLOAT,
    LIFESTYLE_FACTOR FLOAT,
    CLAIMS_HISTORY_FACTOR FLOAT,
    FINAL_PREMIUM DECIMAL(10,2),
    DISCOUNT_APPLIED DECIMAL(8,2),
    FACTOR_BREAKDOWN TEXT,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);


-- ############################################################################
-- SECTION 4: RISK TABLES
-- ############################################################################

CREATE TABLE IF NOT EXISTS INSURANCE_MGMT_SYSTEM.RISK.AT_RISK_POLICIES (
    RISK_ID VARCHAR(20) PRIMARY KEY,
    POLICY_ID VARCHAR(20),
    CUSTOMER_ID VARCHAR(20),
    POLICY_TYPE VARCHAR(20),
    RISK_CATEGORY VARCHAR(30),
    RISK_SCORE FLOAT,
    REVENUE_AT_RISK DECIMAL(12,2),
    CHURN_PROBABILITY FLOAT,
    RISK_DRIVERS TEXT,
    LAST_INTERACTION_DATE DATE,
    DAYS_SINCE_CONTACT INT,
    COMPLAINTS_COUNT INT,
    MISSED_PAYMENTS INT,
    RECOMMENDED_ACTION VARCHAR(200),
    PRIORITY VARCHAR(10),
    IDENTIFIED_DATE DATE,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS INSURANCE_MGMT_SYSTEM.RISK.RISK_FACTORS (
    FACTOR_ID VARCHAR(20) PRIMARY KEY,
    FACTOR_NAME VARCHAR(50),
    FACTOR_CATEGORY VARCHAR(30),
    WEIGHT FLOAT,
    THRESHOLD_LOW FLOAT,
    THRESHOLD_MEDIUM FLOAT,
    THRESHOLD_HIGH FLOAT,
    DESCRIPTION VARCHAR(200),
    APPLIES_TO VARCHAR(50),
    ACTIVE_FLAG BOOLEAN DEFAULT TRUE,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS INSURANCE_MGMT_SYSTEM.RISK.CHURN_PREDICTIONS (
    PREDICTION_ID VARCHAR(20) PRIMARY KEY,
    POLICY_ID VARCHAR(20),
    CUSTOMER_ID VARCHAR(20),
    PREDICTION_DATE DATE,
    CHURN_PROBABILITY FLOAT,
    CONFIDENCE_SCORE FLOAT,
    TOP_RISK_FACTOR VARCHAR(50),
    SECOND_RISK_FACTOR VARCHAR(50),
    PREDICTED_CHURN_DATE DATE,
    RETENTION_OFFER VARCHAR(100),
    OUTCOME VARCHAR(20),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);


-- ############################################################################
-- SECTION 5: ANALYTICS TABLES
-- ############################################################################

CREATE TABLE IF NOT EXISTS INSURANCE_MGMT_SYSTEM.ANALYTICS.CLAIMS_KPI (
    KPI_ID VARCHAR(20) PRIMARY KEY,
    MONTH_YEAR DATE,
    TOTAL_CLAIMS INT,
    CLAIMS_APPROVED INT,
    CLAIMS_DENIED INT,
    CLAIMS_PENDING INT,
    CLAIMS_ESCALATED INT,
    APPROVAL_RATE FLOAT,
    AVG_PROCESSING_DAYS FLOAT,
    AVG_CLAIM_AMOUNT DECIMAL(12,2),
    TOTAL_PAYOUT DECIMAL(14,2),
    FRAUD_DETECTED INT,
    CUSTOMER_SATISFACTION FLOAT,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS INSURANCE_MGMT_SYSTEM.ANALYTICS.POLICY_TRENDS (
    TREND_ID VARCHAR(20) PRIMARY KEY,
    MONTH_YEAR DATE,
    POLICY_TYPE VARCHAR(20),
    NEW_POLICIES INT,
    RENEWED_POLICIES INT,
    CANCELLED_POLICIES INT,
    ACTIVE_POLICIES INT,
    TOTAL_PREMIUM_REVENUE DECIMAL(14,2),
    AVG_PREMIUM DECIMAL(10,2),
    RETENTION_RATE FLOAT,
    GROWTH_RATE FLOAT,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS INSURANCE_MGMT_SYSTEM.ANALYTICS.LOSS_RATIO_HISTORY (
    RECORD_ID VARCHAR(20) PRIMARY KEY,
    POLICY_TYPE VARCHAR(20),
    PLAN_TIER VARCHAR(20),
    MONTH_YEAR DATE,
    PREMIUMS_EARNED DECIMAL(14,2),
    CLAIMS_PAID DECIMAL(14,2),
    LOSS_RATIO FLOAT,
    COMBINED_RATIO FLOAT,
    EXPENSE_RATIO FLOAT,
    TREND VARCHAR(10),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS INSURANCE_MGMT_SYSTEM.ANALYTICS.FRAUD_ALERTS (
    ALERT_ID VARCHAR(20) PRIMARY KEY,
    CLAIM_ID VARCHAR(20),
    POLICY_ID VARCHAR(20),
    CUSTOMER_ID VARCHAR(20),
    ALERT_DATE TIMESTAMP_NTZ,
    FRAUD_TYPE VARCHAR(50),
    CONFIDENCE_SCORE FLOAT,
    ALERT_STATUS VARCHAR(20),
    INVESTIGATION_NOTES TEXT,
    RESOLUTION VARCHAR(30),
    AMOUNT_SAVED DECIMAL(12,2),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

